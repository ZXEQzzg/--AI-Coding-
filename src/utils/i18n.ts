/**
 * Localize day of week string
 */
export function formatDayOfWeek(day: string, lang: Language): string {
  if (lang === 'zh') {
    return day.startsWith('周') ? day : `周${day}`;
  }
  const dayMap: Record<string, string> = {
    周一: 'Mon',
    周二: 'Tue',
    周三: 'Wed',
    周四: 'Thu',
    周五: 'Fri',
    周六: 'Sat',
    周日: 'Sun',
    Mon: 'Mon',
    Tue: 'Tue',
    Wed: 'Wed',
    Thu: 'Thu',
    Fri: 'Fri',
    Sat: 'Sat',
    Sun: 'Sun',
  };
  return dayMap[day] || day;
}

