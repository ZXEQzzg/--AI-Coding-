/**
 * Helper to dynamically format the publisher of an announcement.
 * E.g. "林晨 (房管)" in English mode becomes "林晨 (House Admin)".
 * User's real name (e.g. "林晨") remains untouched, while system role badge is localized.
 */
export function formatPublisherRole(publishedBy: string, lang: Language): string {
  if (!publishedBy) return '';
  const adminBadge = i18n[lang].adminBadge;
  return publishedBy
    .replace(/[\s\u00A0]*[（(]\s*房管\s*[)）]/g, ` (${adminBadge})`)
    .replace(/[\s\u00A0]*[（(]\s*(?:House\s+)?Admin\s*[)）]/gi, ` (${adminBadge})`);
}

